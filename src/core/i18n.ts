const dicts: Record<string, Dict> = { ja, en };

export function t(key: string, vars: Record<string, string> = {}): string {
  const lang = settings.get("ui.language");
  const s = dicts[lang]?.[key] ?? ja[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => vars[k] ?? m);
}
