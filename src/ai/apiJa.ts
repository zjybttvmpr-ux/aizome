// 関数・メソッド・定数が「何をするか」の日本語辞書（行の説明で使う）
//
// 書き方（テンプレート）
//   {0} {1} …  … 引数（『』や「」付きで読みやすく直したもの）
//   {o}        … メソッドを呼んでいる相手（s.upper() の s）
//   {*}        … 引数ぜんぶを「・」でつないだもの
//   {1+}       … 2 つ目から後ろの引数ぜんぶ
//   {@名前}    … キーワード引数（sorted(a, reverse=True) の reverse）
//   {T}        … <型>（GetComponent<Rigidbody>() の Rigidbody）
//   {X?A|B}    … X があれば A、なければ B（A・B の中にも {…} を書ける）
//
// 値の形（名詞）：  "…"             例 "{0} の平方根"
// 動作だけ：       "!…ます"         例 "!{0} 秒待ちます"
// 両方：           ["名詞", "動作", "import の時のひとこと"]
// 込み入ったもの：  (c) => …

export interface ApiCtx {
  /** メソッドを呼んでいる相手（読みやすく直したもの）。関数なら null */
  o: string | null;
  /** 相手の元の文字 */
  rawO: string | null;
  /** 引数（読みやすく直したもの） */
  args: string[];
  /** 引数の元の文字 */
  raw: string[];
  kw: Record<string, string>;
  gen?: string;
}

export type ApiEntry = string | [noun: string | null, verb?: string | null, short?: string] | ((c: ApiCtx) => ApiEntry | null);

export interface ApiTable {
  /** 関数（"len"、"math.sin"、"Mathf.Sqrt" など、呼ぶときの名前のまま） */
  funcs: Record<string, ApiEntry>;
  /** メソッド（名前だけ。何に対して呼んでも同じ説明） */
  methods: Record<string, ApiEntry>;
  /** かっこなしで使う定数（"math.pi" など） */
  consts: Record<string, string>;
  /** かっこなしで使う「相手の〇〇」（.length など） */
  props: Record<string, string>;
  /** import / using したときの説明 */
  modules: Record<string, string>;
}

